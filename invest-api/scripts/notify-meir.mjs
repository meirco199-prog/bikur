// (workflow_dispatch עם text). התגובה נקראת מקובץ האירוע של GitHub (GITHUB_EVENT_PATH) בתוך node — התוכן לא מוזרק ל-shell.
// אבטחה: מתקבלת רק תגובה שכתב בעל הריפו (login = בעל הריפו, author_association = OWNER, לא בוט) ושמתחילה בסמן — כל אחד
// יכול להגיב ב-Issue ציבורי, ותגובה כזו לעולם לא תגיע לטלגרם. הסוד (CRON_SECRET) לא מודפס.
import { readFileSync } from 'node:fs';

export const MARKER = '<!-- notify-meir -->';
export const MAX = 1500;

export function isTrustedNotifyComment(c, owner){
  return !!c && typeof c.body === 'string' && c.body.startsWith(MARKER)
    && !!owner && c.user?.login === owner && c.user?.type !== 'Bot' && c.author_association === 'OWNER';
}

// הטקסט שאחרי הסמן, בלי חתימת Claude Code בסוף (שורת `---` ושורת `_Generated by …_`)
export function extractText(body){
  let s = String(body || '');
  if (s.startsWith(MARKER)) s = s.slice(MARKER.length);
  const lines = s.replace(/\r\n?/g, '\n').split('\n');
  const trimEnd = () => { while (lines.length && !lines[lines.length - 1].trim()) lines.pop(); };
  trimEnd();
  if (lines.length && /^_Generated by .*_$/.test(lines[lines.length - 1].trim())){ lines.pop(); trimEnd(); if (lines.length && /^-{3,}$/.test(lines[lines.length - 1].trim())){ lines.pop(); trimEnd(); } }
  return lines.join('\n').trim();
}

export async function postNotify({ workerUrl, secret, text, fetchImpl = fetch }){
  const res = await fetchImpl(`${workerUrl.replace(/\/$/, '')}/notify?secret=${encodeURIComponent(secret)}`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ text }) });
  const out = await res.json().catch(() => ({ error: `HTTP ${res.status}` }));
  if (!res.ok) throw new Error(`notify ${res.status}: ${String(out.error || '').slice(0, 300)}`);
  return out;
}

async function main(){
  const { GITHUB_EVENT_NAME, GITHUB_EVENT_PATH, REPO_OWNER, WORKER_URL, CRON_SECRET, TEXT } = process.env;
  if (!WORKER_URL) throw new Error('חסר WORKER_URL');
  if (!CRON_SECRET) throw new Error('חסר הסוד CRON_SECRET');
  let text;
  if (GITHUB_EVENT_NAME === 'issue_comment'){
    const ev = JSON.parse(readFileSync(GITHUB_EVENT_PATH, 'utf8'));
    if (!isTrustedNotifyComment(ev.comment, REPO_OWNER)) return { ok: true, skipped: 'לא תגובת notify-meir של בעל הריפו' };
    text = extractText(ev.comment.body);
  } else text = String(TEXT || '').trim();
  if (!text) return { ok: true, skipped: 'טקסט ריק' };
  if (text.length > MAX) throw new Error(`הטקסט ארוך מדי (${text.length} > ${MAX} תווים)`);
  return postNotify({ workerUrl: WORKER_URL, secret: CRON_SECRET, text });
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) main().then((r) => {
  console.log(JSON.stringify(r));
  console.log(`telegram: ${r.telegram || r.skipped}`);
  if (!r.ok) process.exit(1); // not_configured / error → ריצה אדומה, כדי שזה ייראה
}).catch((e) => { console.error('notify-meir failed:', e.message); process.exit(1); });
